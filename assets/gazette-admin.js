/* RMC Advocates – Gazette admin: turns a Kenya Gazette PDF into upload-ready files. Runs entirely in the browser. */
(function(){
  const $ = id => document.getElementById(id);
  const MONTHS = ['january','february','march','april','may','june','july','august','september','october','november','december'];
  let state = null;

  if (window.pdfjsLib){
    pdfjsLib.GlobalWorkerOptions.workerSrc = 'https://cdnjs.cloudflare.com/ajax/libs/pdf.js/3.11.174/pdf.worker.min.js';
  }

  function progress(p, text){
    $('gz-progress').hidden = false;
    $('gz-bar').style.width = Math.round(p * 100) + '%';
    $('gz-prog-text').textContent = text;
  }

  async function extract(file){
    if (!window.pdfjsLib){ alert('The PDF reader could not load. Please check your internet connection and reload this page.'); return; }
    const buf = await file.arrayBuffer();
    progress(0, 'Opening ' + file.name + '…');
    const pdf = await pdfjsLib.getDocument({ data: buf.slice(0) }).promise;
    const pages = [];
    for (let i = 1; i <= pdf.numPages; i++){
      const page = await pdf.getPage(i);
      const tc = await page.getTextContent();
      // Join text fragments using their positions on the page: Gazette PDFs split words into
      // pieces ("G" + "AZETTE", "CXX" + "V" + "II"), so only add a space where there is a visible gap.
      let s = '', prev = null;
      tc.items.forEach(it => {
        if (typeof it.str !== 'string') return;
        if (it.str === ''){ if (it.hasEOL) s += '\n'; return; }
        if (prev){
          const h = Math.max(Math.abs(it.transform[3]) || it.height || 0, Math.abs(prev.transform[3]) || prev.height || 0, 1);
          const dy = Math.abs(it.transform[5] - prev.transform[5]);
          const gap = it.transform[4] - (prev.transform[4] + prev.width);
          if (dy > h * 0.6 || gap < -h * 2){ if (!/\n$/.test(s)) s += '\n'; }
          else if (gap > h * 0.15 && !/\s$/.test(s) && !/^\s/.test(it.str)) s += ' ';
        }
        s += it.str;
        if (it.hasEOL) s += '\n';
        prev = it;
      });
      pages.push(s.replace(/[ \t]+/g, ' ').replace(/ ?\n ?/g, '\n').replace(/\n{3,}/g, '\n\n').trim());
      progress(i / pdf.numPages, 'Reading page ' + i + ' of ' + pdf.numPages + '…');
    }
    const textChars = pages.join('').replace(/\s/g, '').length;
    state = { file, buf, pages };
    detect(pages);
    const notices = GZ.splitNotices(pages).filter(n => n.no);
    $('gz-found').textContent = pdf.numPages + ' pages read · ' + notices.length + ' gazette notices found' +
      (notices.length ? ' (Nos. ' + notices[0].no + ' to ' + notices[notices.length - 1].no + ')' : '') + '.';
    if (textChars < 200 * pdf.numPages * 0.1){
      $('gz-found').textContent += ' Warning: very little text was found. This PDF may be a scan, so search will not work well.';
    }
    progress(1, 'Done. ' + pdf.numPages + ' pages read.');
    $('step2').hidden = false; $('step3').hidden = false;
    $('step2').scrollIntoView({ behavior:'smooth', block:'start' });
  }

  function detect(pages){
    const front = (pages[0] || '') + '\n' + (pages[1] || '');
    const v = front.match(/Vol\.?\s*([CXLVI]+)\s*[—–\-]+\s*No\.?\s*(\d+)/i);
    if (v){ $('f_vol').value = v[1].toUpperCase(); $('f_no').value = v[2]; }
    const d = front.match(/NAIROBI,?\s*(\d{1,2})(?:st|nd|rd|th)?\s+([A-Za-z]+),?\s*(\d{4})/i);
    if (d){
      const m = MONTHS.indexOf(d[2].toLowerCase());
      if (m >= 0) $('f_date').value = d[3] + '-' + String(m + 1).padStart(2, '0') + '-' + String(+d[1]).padStart(2, '0');
    }
    $('f_special').checked = /SPECIAL\s+ISSUE/i.test(front);
  }

  function issueHtml(meta, pages){
    const notices = GZ.splitNotices(pages);
    const nums = notices.filter(n => n.no);
    const date = meta.date, vol = meta.vol, no = meta.no;
    const title = GZ.issueTitle(meta) + ' – ' + GZ.formatDate(date) + ' (Searchable) | RMC Advocates';
    const desc = 'Read, search and download the Kenya Gazette of ' + GZ.formatDate(date) + ' (Vol. ' + vol + ' No. ' + no + ')' +
      (nums.length ? ': ' + nums.length + ' gazette notices, Nos. ' + nums[0].no + ' to ' + nums[nums.length - 1].no : '') +
      '. Unofficial searchable copy.';
    return window.GZ_TEMPLATE
      .split('{{TITLE}}').join(GZ.esc(title))
      .split('{{DESC}}').join(GZ.esc(desc))
      .split('{{CANONICAL}}').join('https://www.rmc-advocates.com/' + meta.page)
      .split('{{BODY}}').join(GZ.renderIssueBody(meta, notices));
  }
  function textJsFor(slug, data){
    return '(window.GZ_TEXT = window.GZ_TEXT || {})[' + JSON.stringify(slug) + '] = ' + JSON.stringify(data) + ';\n';
  }
  function issuesJsFor(list, date){
    list.sort((a, b) => (b.date || '').localeCompare(a.date || '') || (+b.no) - (+a.no));
    return '/* Kenya Gazette issues list – generated by gazette-admin.html on ' + date + '. */\nwindow.GAZETTE_ISSUES = ' + JSON.stringify(list, null, 2) + ';\n';
  }

  function download(blob, name){
    const a = document.createElement('a');
    a.href = URL.createObjectURL(blob); a.download = name;
    document.body.appendChild(a); a.click();
    setTimeout(() => { URL.revokeObjectURL(a.href); a.remove(); }, 4000);
  }

  async function build(){
    if (!state) return;
    const vol = $('f_vol').value.trim().toUpperCase(), no = $('f_no').value.trim(), date = $('f_date').value, special = $('f_special').checked;
    if (!vol || !no || !date){ alert('Please fill in the volume, number and date of the issue.'); return; }
    if (!window.JSZip){ alert('The ZIP tool could not load. Please check your internet connection and reload this page.'); return; }

    const slug = 'kenya-gazette-' + date + '-vol-' + vol.toLowerCase() + '-no-' + no + (special ? '-special' : '');
    const notices = GZ.splitNotices(state.pages);
    const nums = notices.filter(n => n.no);
    const meta = {
      slug, vol, no, date, special,
      pdf: 'gazette/pdf/' + slug + '.pdf',
      page: slug + '.html',
      text: 'gazette/text/' + slug + '.js',
      pages: state.pages.length,
      notices: nums.length,
      size: state.file.size,
      added: new Date().toISOString().slice(0, 10)
    };

    const html = issueHtml(meta, state.pages);

    const textJs = textJsFor(slug, { pages: state.pages });

    const list = (window.GAZETTE_ISSUES || []).filter(i => i.slug !== slug);
    list.push(meta);
    const issuesJs = issuesJsFor(list, meta.added);

    $('gz-build-msg').textContent = 'Creating bundle…';
    const zip = new JSZip();
    zip.file(meta.page, html);
    zip.file(meta.text, textJs);
    zip.file('gazette/issues.js', issuesJs);
    zip.file(meta.pdf, state.buf);
    const blob = await zip.generateAsync({ type:'blob', compression:'DEFLATE', compressionOptions:{ level:6 } });
    download(blob, 'gazette-upload-' + slug + '.zip');
    $('gz-build-msg').textContent = 'Bundle downloaded: gazette-upload-' + slug + '.zip (' + GZ.fmtSize(blob.size) + '). ' +
      'The website will list ' + list.length + ' issue' + (list.length === 1 ? '' : 's') + ' after you upload it.';
    window.GZ_LAST_BUILD = { meta, html, textJs, issuesJs };
  }

  /* ---------- Remove or correct a notice ---------- */
  const rmIssue = $('rm-issue');
  if (rmIssue){
    const issues = (window.GAZETTE_ISSUES || []).slice().sort((a, b) => (b.date || '').localeCompare(a.date || ''));
    rmIssue.innerHTML = issues.length ? issues.map(i => '<option value="' + GZ.esc(i.slug) + '">' + GZ.esc(GZ.issueTitle(i) + ' – ' + GZ.formatDate(i.date)) + '</option>').join('')
      : '<option value="">No issues uploaded yet</option>';
    let current = null;
    const radios = () => document.querySelector('input[name="rm-action"]:checked').value;
    document.querySelectorAll('input[name="rm-action"]').forEach(r => r.addEventListener('change', () => { $('rm-text').readOnly = radios() !== 'correct'; }));

    $('rm-load').addEventListener('click', async () => {
      const issue = issues.find(i => i.slug === rmIssue.value);
      const no = $('rm-no').value.replace(/\D/g, '');
      $('rm-edit').hidden = true; current = null;
      if (!issue || !no){ $('rm-found').textContent = 'Choose an issue and enter the notice number.'; return; }
      let data;
      try { data = await GZ.loadText(issue); }
      catch(e){ $('rm-found').textContent = 'Could not load this issue’s text. Run this page from your website folder (it must contain ' + issue.text + ').'; return; }
      const n = GZ.splitNotices(data.pages).find(x => x.no === no);
      if (!n){ $('rm-found').textContent = 'Gazette Notice No. ' + no + ' was not found in ' + GZ.issueTitle(issue) + '.'; return; }
      current = { issue, data, no };
      $('rm-text').value = n.text;
      $('rm-text').readOnly = radios() !== 'correct';
      $('rm-pdf').checked = false;
      $('rm-found').textContent = 'Found Gazette Notice No. ' + no + ' on page ' + n.page + '.';
      $('rm-msg').textContent = '';
      $('rm-edit').hidden = false;
    });

    $('rm-build').addEventListener('click', async () => {
      if (!current) return;
      if (!window.JSZip){ alert('The ZIP tool could not load. Please check your internet connection and reload this page.'); return; }
      const { issue, data, no } = current;
      const action = radios();
      let replacement;
      if (action === 'remove') replacement = 'GAZETTE NOTICE NO. ' + no + '\n' + GZ.REMOVED_NOTE;
      else {
        replacement = $('rm-text').value.trim();
        if (!/^GAZETTE\s+NOTICE\s+NO\.?\s*\d+/.test(replacement)) replacement = 'GAZETTE NOTICE NO. ' + no + '\n' + replacement;
      }
      const pages = GZ.replaceNotice(data.pages, no, replacement);
      if (!pages){ $('rm-msg').textContent = 'The notice could not be located in the text. Nothing was changed.'; return; }
      const today = new Date().toISOString().slice(0, 10);
      const newData = { pages, edits: (data.edits || []).concat([{ no, action, date: today }]) };
      const meta = Object.assign({}, issue);
      const withdrawPdf = $('rm-pdf').checked && meta.pdf;
      const oldPdf = meta.pdf;
      if (withdrawPdf){ meta.pdf = ''; meta.pdfWithdrawn = today; }
      const list = (window.GAZETTE_ISSUES || []).map(i => i.slug === meta.slug ? meta : i);

      const zip = new JSZip();
      zip.file(meta.page, issueHtml(meta, pages));
      zip.file(meta.text, textJsFor(meta.slug, newData));
      zip.file('gazette/issues.js', issuesJsFor(list, today));
      const blob = await zip.generateAsync({ type:'blob', compression:'DEFLATE' });
      const name = 'gazette-update-' + meta.slug + '-notice-' + no + '.zip';
      download(blob, name);

      // keep this session consistent for further edits
      window.GZ_TEXT[meta.slug] = newData; window.GAZETTE_ISSUES = list;
      issues.splice(issues.findIndex(i => i.slug === meta.slug), 1, meta);
      current = null; $('rm-edit').hidden = true;
      $('rm-found').textContent = '';
      $('rm-msg').textContent = '';
      $('rm-found').textContent = 'Bundle downloaded: ' + name + '. Unzip it into your website folder and upload the 3 files' +
        (withdrawPdf ? ', then delete ' + oldPdf + ' from your web host' : '') +
        '. Record the action and date in the request register, and reply to the requester.';
    });
  }

  $('gz-file').addEventListener('change', e => { const f = e.target.files[0]; if (f) extract(f).catch(err => { progress(0, 'Could not read this PDF: ' + err.message); }); });
  const drop = $('gz-drop');
  ['dragover','dragenter'].forEach(ev => drop.addEventListener(ev, e => { e.preventDefault(); drop.classList.add('over'); }));
  ['dragleave','drop'].forEach(ev => drop.addEventListener(ev, e => { e.preventDefault(); drop.classList.remove('over'); }));
  drop.addEventListener('drop', e => { const f = e.dataTransfer.files[0]; if (f) extract(f).catch(err => progress(0, 'Could not read this PDF: ' + err.message)); });
  $('gz-build').addEventListener('click', () => build().catch(err => { $('gz-build-msg').textContent = 'Something went wrong: ' + err.message; }));
})();
